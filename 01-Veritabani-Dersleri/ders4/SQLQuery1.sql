USE UYGULAMAx
GO

DROP FUNCTION IF EXISTS DBO.KarakterYaz2
GO

CREATE FUNCTION dbo.KarakterYaz2(@AlfaValue NVARCHAR(MAX),@ADET INT)
RETURNS NVARCHAR(MAX)
AS BEGIN

DECLARE @KARAKTER NVARCHAR(MAX)=''
DECLARE @SAYAC INT =1

WHILE @SAYAC<=@ADET
BEGIN
	SET @KARAKTER=@KARAKTER+@AlfaValue
	SET @SAYAC=@SAYAC+1
END

return @KARAKTER
END