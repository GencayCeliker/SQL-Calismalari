GO

CREATE FUNCTION dbo.ASALOKUL(@SAYI INT)
RETURNS NVARCHAR(MAX)
AS BEGIN
	DECLARE @SONUC NVARCHAR(MAX)
	DECLARE @SAYAC INT=2
	WHILE @SAYAC<=@SAYI-1
		BEGIN
			IF @SAYI%@SAYAC=0
				SET @SONUC='ASAL DEĞİL'
			SET @SAYAC=@SAYAC+1
		END
RETURN @SONUC
END