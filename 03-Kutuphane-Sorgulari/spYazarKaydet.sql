USE KUTUPHANE
GO
DROP PROCEDURE IF EXISTS dbo.spYazarKaydet
GO
SET NOCOUNT ON
GO
CREATE PROCEDURE spYazarKaydet
@YazarAdSoyad NVARCHAR(250)
AS
IF NOT EXISTS (SELECT YazarAdSoyad FROM TBL_YAZARLAR 
WHERE UPPER(YazarAdSoyad) = UPPER(@YazarAdSoyad))

INSERT INTO TBL_YAZARLAR VALUES
(@YazarAdSoyad)

ELSE RETURN -1