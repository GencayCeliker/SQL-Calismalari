USE KUTUPHANE
GO
CREATE TABLE TBL_OdemeTuru
(
OTId INT IDENTITY PRIMARY KEY,
OTAciklama NCHAR(1) CHECK (OTAciklama IN('A','B')),-- A yada B Yazılabilir
)
GO

CREATE TABLE TBL_Kasa
(
KasaId INT IDENTITY PRIMARY KEY,
UyeId INT FOREIGN KEY REFERENCES TBL_UYELER(UyeId),
OTId INT FOREIGN KEY REFERENCES TBL_OdemeTuru(OTId),
OTarih DATETIME,
Miktar SMALLMONEY,
)