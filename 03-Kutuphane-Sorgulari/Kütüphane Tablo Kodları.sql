CREATE DATABASE KUTUPHANE

USE KUTUPHANE
GO
CREATE TABLE TBL_YAZARLAR
(
YazarId INT IDENTITY PRIMARY KEY,
YazarAdSoyad NVARCHAR(250)
)
GO

USE KUTUPHANE
GO
CREATE TABLE TBL_UYELER
(
UyeId INT IDENTITY PRIMARY KEY,
UyeAd NVARCHAR(250) NOT NULL,
UyeSoyad NVARCHAR(250) NOT NULL,
UyeTCKimlik NCHAR(11) UNIQUE CHECK(UyeTCKimlik LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-2-4-6-8]')NOT NULL,
UyeAdres NVARCHAR(500) NOT NULL,
UyeTel NCHAR(10) NOT NULL
)
GO

USE KUTUPHANE
GO
CREATE TABLE TBL_Kitaplar
(
KitapId INT PRIMARY KEY IDENTITY,
ISBN NCHAR(13) CHECK(ISBN LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]') UNIQUE NOT NULL,
KitapAdi NVARCHAR(250) NOT NULL,
Sayfa INT NOT NULL,
Adet INT NOT NULL,
YazarId INT FOREIGN KEY REFERENCES TBL_YAZARLAR(YazarId)
)
GO

USE KUTUPHANE
GO
CREATE TABLE TBL_UYEKITAP
(
UKId INT IDENTITY PRIMARY KEY,
KitapId INT FOREIGN KEY REFERENCES TBL_Kitaplar(KitapId),
UyeId INT FOREIGN KEY REFERENCES TBL_UYELER(UyeId),
OVTarihi DATETIME NOT NULL,
GATarihi DATETIME
)