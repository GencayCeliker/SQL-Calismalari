CREATE TRIGGER trgMaasGuncelle
ON PERSONEL
FOR INSERT
AS BEGIN
 DECLARE @PID INT = (SELECT PID FROM inserted)
 DECLARE @CYARDIM INT = (SELECT CSayisi FROM inserted)*2000
 DECLARE @Kira INT = 0
 DECLARE @UNVAN INT = (SELECT Unvan FROM inserted)
 DEClare @Tazminat Int=(SELECT Tazminat FROM UNVANLAR WHERE UnvanID=@UNVAN)
IF(SELECT Kira FROM inserted)=1 SET @Kira = 50000
DECLARE @MAAS INT =20000+@CYARDIM+@Kira+@UNVAN+@Tazminat
INSERT INTO MAASLAR VALUES(@PID , @MAAS)
END




