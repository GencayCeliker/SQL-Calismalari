)
CREATE TABLE PERSONEL
(
PID INT IDENTITY PRIMARY KEY,
PAdi NVARCHAR (100),
PSoyadi NVARCHAR (100),
TCKimlik NCHAR(11),
Unvan INT FOREIGN KEY REFERENCES UNVANLAR(UnvanID),
CSayisi INT,
Kira BIT
)
CREATE TABLE MAASLAR
(
MaasID INT IDENTITY PRIMARY KEY,
PID INT FOREIGN KEY REFERENCES PERSONEL(PID),
Maas INT
)
